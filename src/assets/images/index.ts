export function resolveLocalImage(value: string): string {
  if (typeof value !== 'string') return value;
  return LOCAL_IMAGE_PATH_MAP[value] || value;
}

export function resolveLocalImagesDeep<T>(input: T): T {
  if (typeof input === 'string') {
    return resolveLocalImage(input) as unknown as T;
  }
  if (Array.isArray(input)) {
    return input.map((item) => resolveLocalImagesDeep(item)) as unknown as T;
  }
  if (input && typeof input === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(input as Record<string, unknown>)) {
      out[k] = resolveLocalImagesDeep(v);
    }
    return out as T;
  }
  return input;
}
